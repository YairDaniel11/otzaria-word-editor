/**
 * פס הדגימה של בורר הגופן — מה מוצג בו, ומתי הוא נקרא.
 *
 * המשתמש מסמן קטע ופותח את רשימת הגופנים; בתחתית הרשימה מופיע הטקסט שהוא סימן,
 * בגופן שהסימון עומד עליו. זה מה שהוא בא לדעת — „איך זה ייראה **בטקסט שלי**”
 * — והוא מקבל את זה בלי שהמסמך ייגע.
 *
 * ## למה זה ולא צביעה של המסמך עצמו
 *
 * זו לא בחירה סגנונית אלא תוצאה של מדידה. שלושה מסלולים לצביעה במסמך נמדדו
 * בכרום אמיתי, והרשומה המלאה ב-`docs/engine-gaps.md` („תצוגה חיה של גופן”).
 * בקצרה: מסלול אחד קונה דרגות undo ומסמן „לא נשמר”, ושני האחרים נקיים לגמרי
 * כלפי המסמך — docx זהה בייט-בבייט — ובכל זאת **מטעים**, מפני שהמנוע אינו זורם
 * מחדש: הטקסט יוצא מהעמוד ונחתך, והצביעה גסה מהבחירה (9 תווים שנבחרו, ריצה של
 * 23 שנצבעת).
 *
 * הפס אינו יכול להטעות באותו אופן, מפני שאין בו עימוד לשקר עליו. הוא מראה
 * אותיות, וזה כל מה שהוא מתיימר להראות.
 *
 * ## מה כאן, ומה במפורש לא
 *
 * כאן ההחלטה **מה** מוצג ו**מתי** נקרא. הקריאה עצמה היא
 * `engine/font-preview.ts` (`readSelectionText`), והמסירה לפקד היא
 * `use-font-controls.ts`. אותה חלוקה בדיוק של `createFontPreview` לידו: מודול
 * שאין לו מנוע ואין לו DOM אפשר לבדוק, ומודול שיש לו את שניהם אי אפשר.
 */
import { computed, ref, type ComputedRef } from 'vue';

/**
 * מה שהפס מציג כשהסמן מכווץ ואין טקסט מסומן — הפנגרם העברי, שכולל את כל אותיות
 * האלפבית ולכן מראה את הגופן ולא רק כמה אותיות ממנו.
 *
 * **ובכוונה לא ב-`src/ui/ribbon/`:** `tests/unit/menu-locale-coverage.test.ts`
 * סורק שם כל מחרוזת עברית ודורש לה מקבילה אנגלית ב-`i18n.ts`, ומשפט שכל תפקידו
 * להראות אותיות עבריות חייב להישאר עברי בכל שפה. זו אותה הנמקה שבגללה דגימת
 * האותיות שבשורות עצמן כתובה כ-`content` ב-CSS ולא כטקסט בתבנית.
 */
export const FONT_SAMPLE_FALLBACK = 'דג סקרן שט בים מאוכזב ולפתע מצא חברה';

/**
 * תקרת אורך לדגימה.
 *
 * ה-CSS ממילא קוטע בשלוש נקודות, ולכן זו אינה שאלה של תצוגה אלא של מה שנדחף
 * אל תוך ה-DOM: `Ctrl+A` על ספר שלם היה מוסר לכאן פרק בצומת טקסט אחד, שנבנה
 * מחדש בכל תזוזה של הסימון.
 */
export const FONT_SAMPLE_MAX_CHARS = 60;

export interface FontSampleDeps {
  /** קוראת את הטקסט המסומן. `''` = אין, ואז מוצג `FONT_SAMPLE_FALLBACK`. */
  read: () => Promise<string>;
}

export interface FontSample {
  /** מה שמוצג בפס. לעולם אינו ריק — בהיעדר בחירה זו ברירת המחדל. */
  text: ComputedRef<string>;
  /**
   * הרשימה נפתחה, או שהסימון בה זז. קריאה חוזרת באותו סבב אינה עושה דבר —
   * ראו „פעם אחת לסבב”.
   */
  begin: () => void;
  /** הרשימה נסגרה. הסבב הבא ייקרא מחדש. */
  end: () => void;
}

/**
 * ## פעם אחת לסבב, ולא בכל ריחוף
 *
 * הקריאה נמדדה כזולה (1ms), ולכן זה אינו שיקול ביצועים אלא שיקול נכונות:
 * הריחוף עצמו אינו משנה את הבחירה, וקריאה חוזרת הייתה מחליפה את הדגימה מתחת
 * לאצבע אילו משהו אחר הזיז את הסמן בזמן שהרשימה פתוחה. אותה הנמקה שבגללה
 * `RibbonCombo` מקפיא את רשימת האפשרויות ברגע שמתחילים להקליד בה.
 *
 * ## ולמה מונה סבבים, ולא דגל „נקרא”
 *
 * הקריאה אסינכרונית, והרשימה יכולה להיסגר בזמן שהיא באוויר. דגל בודד היה נותן
 * לתשובה המאוחרת לנחות אחרי הסגירה — כלומר להציב טקסט בפס של הסבב **הבא**,
 * לרגע אחד, עד שהקריאה החדשה תחזור. המונה מזהה את הסבב שהקריאה יצאה ממנו,
 * וזורק כל מה שאיחר.
 */
export function createFontSample(deps: FontSampleDeps): FontSample {
  const selected = ref('');
  let round = 0;
  let read = false;

  async function load(): Promise<void> {
    if (read) return;
    read = true;
    const mine = round;
    const text = await deps.read();
    if (mine === round) selected.value = text;
  }

  return {
    text: computed(() => {
      const trimmed = selected.value.trim();
      if (trimmed === '') return FONT_SAMPLE_FALLBACK;
      // `Array.from` ולא `slice`: חיתוך לפי יחידות קוד היה יכול לפצל זוג
      // surrogate ולהשאיר ‎`U+FFFD`‎ בסוף הדגימה.
      const chars = Array.from(trimmed);
      return chars.length > FONT_SAMPLE_MAX_CHARS
        ? chars.slice(0, FONT_SAMPLE_MAX_CHARS).join('')
        : trimmed;
    }),
    begin: () => void load(),
    end: () => {
      round += 1;
      read = false;
      selected.value = '';
    },
  };
}
