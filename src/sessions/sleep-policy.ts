/**
 * מתי מותר לשחרר את המנוע של מסמך שברקע — „טאב נרדם”.
 *
 * ## למה זה מודול ולא תנאי במעטפת
 *
 * שחרור מנוע הוא **מחיקה של כל מה שהמסמך מחזיק בזיכרון**: התוכן, היסטוריית
 * ה-Undo, ומצב העריכה. מה שמצדיק אותו הוא הנחה אחת בלבד — שכל מה שאבד ניתן
 * לקריאה בחזרה ממקום אחר (הקובץ בדיסק, הטיוטה במרחב הפרטי, הסמן ברשומה). אם
 * ההנחה הזאת אינה מתקיימת אפילו פעם אחת, המשתמש מאבד עבודה בלי שביקש דבר
 * ובלי שראה אזהרה.
 *
 * זהו בדיוק סוג הקוד שהפרויקט מוציא מהמעטפת (ראו open-flow.ts): החלטה
 * שקובעת אם עבודה נמחקת חייבת להיות נבדקת, והמעטפת עצמה אינה מכוסה. תנאי
 * `if` שנשמט כאן אינו נראה בשום מסך.
 *
 * ## הסיבות אינן קישוט
 *
 * ההחלטה מחזירה **למה** ולא רק „לא”. שתי סיבות מהן מעניינות מאוד כשהן חוזרות
 * ונשנות — `unwritten-work` פירושה שהטיוטה אינה נכתבת (מסמך גדול מהמכסה, גשר
 * שנפל), ו-`no-file` פירושה מסמך שכל קיומו תלוי בטיוטה שלו — ולכן הן נאמרות
 * בשם ולא נבלעות ב-`false`.
 */

/** מה שידוע על הטאב ברגע ההחלטה. */
export interface SleepCandidate {
  /** האם זה הטאב שעל המסך. */
  isActive: boolean;
  /** האם הוא כבר ממתין לטעינה — כלומר אין לו מנוע לשחרר. */
  isPending: boolean;
  /** האם יש בו מסמך פתוח בפועל. */
  hasEngine: boolean;
  /** האם פתיחה רצה בו כרגע. */
  isOpening: boolean;
  /** האם סבב שמירה רץ בו כרגע — הוא מייצא מהמנוע הזה ממש עכשיו. */
  isSaving: boolean;
  /** האם הרשומה שלו נושאת קובץ. מסמך חדש שלא נשמר מעולם — `false`. */
  hasFile: boolean;
  /**
   * האם יש בו עבודה שאינה בדיסק וגם אינה בטיוטה. נשאל **אחרי** `flush`
   * (ראו `SessionKeeper.hasUnwrittenWork`), ולכן `true` כאן פירושו שכתיבת
   * הטיוטה לא הצליחה — לא שהיא טרם נוסתה.
   */
  hasUnwrittenWork: boolean;
}

/** למה הטאב נשאר בזיכרון. */
export type SleepRefusal =
  /** זה המסמך שעל המסך. */
  | 'active'
  /** אין מנוע לשחרר: הוא כבר ממתין לטעינה, או שלא נפתח בו דבר. */
  | 'no-engine'
  /** פתיחה או שמירה רצות בו ברגע זה, ושתיהן עובדות על המנוע. */
  | 'busy'
  /**
   * אין לו קובץ. העותק היחיד שלו בעולם הוא הטיוטה שלו, והשם שהמשתמש נתן לו
   * אינו נשמר ברשומה כלל — הרדמה הייתה עושה את הטיוטה לנקודת כשל יחידה,
   * ומחזירה אותו בשם „מסמך חדש”.
   */
  | 'no-file'
  /**
   * יש בו עבודה שלא נכתבה לשום מקום. זהו השער האחרון, והוא זה שהופך את
   * המנגנון כולו לבטוח: מסמך שגדול מהמכסה של הטיוטה, או שהכתיבה שלו נכשלה,
   * **נשאר בזיכרון** — עדיף לשלם בזיכרון מאשר בעבודה של המשתמש.
   */
  | 'unwritten-work';

export type SleepDecision = { action: 'sleep' } | { action: 'keep'; reason: SleepRefusal };

/**
 * האם להרדים.
 *
 * הסדר אינו שרירותי: הזול והוודאי קודם (מי על המסך, יש בכלל מה לשחרר), ומה
 * שדורש ידיעה על העבודה עצמה — אחרון. `hasUnwrittenWork` נכון רק אחרי
 * `flush`, ולכן הוא נשאל בסוף ולא בהתחלה.
 */
export function decideSleep(candidate: SleepCandidate): SleepDecision {
  if (candidate.isActive) return { action: 'keep', reason: 'active' };
  if (candidate.isPending || !candidate.hasEngine) return { action: 'keep', reason: 'no-engine' };
  if (candidate.isOpening || candidate.isSaving) return { action: 'keep', reason: 'busy' };
  if (!candidate.hasFile) return { action: 'keep', reason: 'no-file' };
  if (candidate.hasUnwrittenWork) return { action: 'keep', reason: 'unwritten-work' };
  return { action: 'sleep' };
}
